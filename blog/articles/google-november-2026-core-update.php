<h2 id="what-is-confirmed">What Google has confirmed about the November 2026 core update</h2>
<ul>
    <li><strong>Start date:</strong> November 10, 2026, logged on the <a href="https://status.search.google.com/incidents/WLxcJyC6jMWMfryxsKMc" target="_blank" rel="noopener">Google Search Status Dashboard</a>.</li>
    <li><strong>Scope:</strong> global, across all languages—so it affects searches in India, including Hindi and Marathi results.</li>
    <li><strong>Duration:</strong> up to two weeks, which points to completion around November 24. As of November 14, the dashboard still listed the update as active.</li>
    <li><strong>Third of 2026:</strong> the March 2026 core update ran from March 27 to April 8, and the May 2026 core update ran from May 21 to June 2. Both took about 12 days.</li>
    <li><strong>No new guidance:</strong> Google has not shared update-specific advice. Its existing <a href="https://developers.google.com/search/updates/core-updates" target="_blank" rel="noopener">core updates documentation</a> still applies.</li>
</ul>

<h2 id="what-is-a-core-update">What is a Google core update, in simple terms?</h2>
<p>A core update is a broad change to how Google's ranking systems assess content across the whole web. It is not a penalty and it does not target one website, industry or tactic. Google's own documentation says that, in general, most sites do not need to worry about core updates and may not even notice one has happened.</p>

<p>When rankings change after a core update, it usually means Google's systems now judge other pages to be more useful for a query—not that your page "broke" a rule. That is why there is rarely a single technical fix. Google's long-standing position is that pages which drop after a core update may have nothing specifically wrong to fix.</p>

<p>Core updates are also different from spam updates and from technical problems such as a site being blocked from crawling. If your pages disappeared from Google entirely, look at indexing first using our <a href="/blog/technical-seo-checklist-new-website">technical SEO checklist</a>.</p>

<h2 id="when-to-check">When should you check your rankings?</h2>
<p>Rankings often swing up and down during a rollout, so early numbers are unreliable. A sensible timeline:</p>
<ol>
    <li><strong>Wait for completion.</strong> Google updates its Search Status Dashboard and ranking release history when the rollout finishes.</li>
    <li><strong>Wait at least one more full week.</strong> This gives you a clean week of data after the change.</li>
    <li><strong>Compare like for like.</strong> In Google Search Console, compare that week with the week before November 10. Weekdays and weekends behave differently, so compare full weeks.</li>
</ol>
<p>Making large changes in the middle of a rollout makes it impossible to tell whether the update or your edit caused what you see next.</p>

<h2 id="if-traffic-dropped">If your traffic dropped: a step-by-step check</h2>

<h3>1. Confirm the drop is real and matches the update</h3>
<p>Open Search Console → Performance → Search results. Set the date comparison described above. If the decline started around November 10, the update is a likely cause. If it started earlier, check for other reasons: a site redesign, slower hosting, a broken page, seasonal demand or a tracking change.</p>

<h3>2. Find which pages and queries lost visibility</h3>
<p>Switch to the Pages tab and sort by the change in clicks. Then check the Queries tab for those pages. A small dip of one or two positions is common after any core update. A large, sustained drop across many pages deserves a deeper review.</p>

<h3>3. Review the pages that dropped most, honestly</h3>
<p>Google recommends assessing whether your content is helpful, reliable and made for people first. For each affected page, ask:</p>
<ul>
    <li>Does it give original information, real experience or clear analysis—or does it repeat what other pages already say?</li>
    <li>Would a customer trust it? Is it clear who wrote it, and are claims backed by sources?</li>
    <li>Does it fully answer the question in the search, or does it hide the answer below filler?</li>
    <li>Is it up to date? Old prices, dead links and outdated screenshots reduce trust.</li>
    <li>Was it written mainly to attract search traffic rather than to help a visitor?</li>
</ul>
<p>Google also suggests asking someone unconnected to your business for an honest opinion. Owners are often too close to their own pages.</p>

<h3>4. Improve the content, not just the keywords</h3>
<p>Useful improvements include adding real examples from your work, clearer pricing or process details, an author line, FAQs that answer actual customer questions, and removing thin or duplicated pages. Avoid stuffing more keywords into the same text; that does not address what a core update measures.</p>

<h3>5. Be patient</h3>
<p>Recovery is not instant. Some improvements are reflected over the following weeks, while larger gains often show up only around a later core update. Keep improving steadily rather than rewriting the whole site at once.</p>

<h2 id="what-not-to-do">What not to do during the rollout</h2>
<ul>
    <li><strong>Do not panic-delete pages.</strong> Removing content because of a two-day dip can lose rankings you would have kept.</li>
    <li><strong>Do not buy backlinks or "recovery packages".</strong> Paid link schemes break Google's spam policies and can make things worse.</li>
    <li><strong>Do not change URLs or redesign mid-rollout.</strong> You will not be able to measure what happened.</li>
    <li><strong>Do not trust anyone who promises a guaranteed number one ranking.</strong> No one outside Google controls rankings.</li>
</ul>

<h2 id="local-business">What it means for local and service businesses in India</h2>
<p>If you run a clinic, coaching class, real estate firm, manufacturer or agency in a city like Pune, most of your enquiries usually come from local searches and your Google Business Profile, not only from blog traffic. Check both:</p>
<ul>
    <li><strong>Service pages:</strong> does each page clearly say what you do, where you serve, what it costs or how pricing works, and how to contact you?</li>
    <li><strong>Google Business Profile:</strong> are your categories, service areas, hours, photos and reviews current? Local map results are a separate system, so a website drop does not always mean your profile dropped.</li>
    <li><strong>AI answers:</strong> Google's AI features use the same index, so clear, well-structured pages help there too. Read our guide on <a href="/blog/google-ai-mode-seo-small-businesses-2026">appearing in Google AI Mode</a>.</li>
</ul>

<h2>The practical takeaway</h2>
<p>The November 2026 core update is a normal, broad ranking change. Wait for it to finish, wait one more week, measure carefully in Search Console, and then improve the pages that lost the most visibility with genuinely more useful content. Most websites need steady, honest improvement—not emergency fixes.</p>

