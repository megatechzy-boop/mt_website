<h2>Current ChatGPT Ads pricing models</h2>
<p>OpenAI's <a href="https://help.openai.com/en/articles/20001210-create-campaigns-for-chatgpt">campaign documentation</a> currently describes three objectives:</p>
<ul>
    <li><strong>CPM:</strong> cost per 1,000 impressions, designed for scale, reach and awareness.</li>
    <li><strong>CPC:</strong> cost per valid click, designed for engagement and website traffic.</li>
    <li><strong>oCPC:</strong> conversion-optimized cost per click, billed per valid click while optimizing toward a selected conversion event.</li>
</ul>
<p>The objective changes both how the campaign is charged and what delivery attempts to optimize.</p>

<h2>How to calculate CPC and CPM</h2>
<p><strong>Average CPC = total spend divided by valid clicks.</strong> If a campaign spends ₹10,000 and records 200 valid clicks, its average CPC is ₹50. This is a mathematical example, not a platform benchmark.</p>
<p><strong>CPM = total spend divided by impressions, multiplied by 1,000.</strong> If ₹20,000 produces 500,000 impressions, the effective CPM is ₹40. Again, this is an example for understanding the formula.</p>

<h2>Daily budget vs campaign-total budget</h2>
<p>A campaign-total budget caps planned spend across the campaign duration. A daily budget is the average amount the campaign aims to spend per day over a seven-day period. According to OpenAI's billing guidance, daily spend may reach up to twice the selected daily budget on an individual day while remaining within the applicable seven-day limit.</p>
<p>Businesses that need a strict total test ceiling may prefer a campaign-total budget. Teams using daily budgets should understand pacing rules and monitor billing rather than treating the displayed daily amount as a same-day maximum.</p>

<h2>Do official CPC benchmarks exist?</h2>
<p>OpenAI says ChatGPT Ads is still an early platform and does not yet have performance benchmarks across advertisers, industries or campaign types. Any universal claim that ChatGPT Ads always cost a particular number of rupees per click should be treated cautiously.</p>
<p>Ads Manager may provide bidding guidance, and OpenAI's current advertiser basics mention a suggested starting maximum CPC bid in US dollars. That is a bid recommendation, not a guaranteed average price, an India benchmark or a promised result.</p>

<h2>Measure the metrics that connect spend to revenue</h2>
<h3>Cost per lead</h3>
<p><strong>CPL = advertising spend divided by leads.</strong> A ₹15,000 campaign producing 30 leads has a ₹500 CPL.</p>
<h3>Cost per qualified lead</h3>
<p>If only 10 of those leads match the service, location and budget criteria, the qualified CPL is ₹1,500. This is usually more useful than the raw lead count.</p>
<h3>Customer acquisition cost</h3>
<p><strong>CAC = advertising spend divided by new customers.</strong> A ₹30,000 campaign that creates five customers has a ₹6,000 media CAC. Compare that figure with gross profit, sales effort and customer lifetime value.</p>

<h2>How to choose a test budget</h2>
<ol>
    <li>Estimate the value of a qualified lead and a new customer.</li>
    <li>Choose one offer and one primary conversion.</li>
    <li>Set a loss limit the business can afford while learning.</li>
    <li>Allow enough room for multiple creatives and meaningful delivery.</li>
    <li>Define in advance what would justify pausing, improving or scaling.</li>
</ol>
<p>A small test is useful only when it can generate enough signal to support a decision. A large test is risky when tracking, the landing page or sales follow-up is weak.</p>

<h2>Example: evaluating a ₹25,000 campaign</h2>
<p>Suppose a business spends ₹25,000, receives 250 clicks, generates 20 leads, identifies five qualified leads and closes two customers. The average CPC is ₹100, raw CPL is ₹1,250, qualified CPL is ₹5,000 and media CAC is ₹12,500.</p>
<p>Those figures become meaningful only when compared with customer value and fulfilment margin. A ₹12,500 CAC may be attractive for a high-value contract and unsustainable for a low-margin transaction.</p>

<h2>Ways to reduce wasted spend</h2>
<ul>
    <li>Promote a specific offer rather than every service.</li>
    <li>Keep ad groups tightly connected to one customer need.</li>
    <li>Use a landing page that matches the ad promise.</li>
    <li>Test tracking before launch and review lead quality weekly.</li>
    <li>Pause weak combinations instead of increasing budget to force delivery.</li>
</ul>

<h2>Frequently asked questions</h2>
<h3>Does ChatGPT Ads use prepaid billing?</h3>
<p>OpenAI currently describes a postpay model in which spend accrues and the saved payment method is charged according to the account's payment threshold.</p>
<h3>Should I use CPC or CPM?</h3>
<p>Use CPC when qualified site traffic is the main objective. Use CPM when reach and awareness are the primary goal. Use oCPC only when conversion measurement is ready and the campaign should optimize toward a supported action.</p>

