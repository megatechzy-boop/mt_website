<h2 id="what-trial-reels-do">What Trial Reels actually do</h2>

<p>Trial Reels let a creator test a Reel with people who do not follow the account before deciding whether to share it more widely. Meta says a trial is not initially placed on the creator's main profile grid or Reels tab for other people to browse, although followers may still encounter it through sharing or related surfaces.</p>

<p>Performance information normally becomes available after the trial has gathered data. The creator can then share the Reel with everyone or, where available, use an automatic sharing option based on early performance. Trial Reels are useful for testing a new topic, format or storytelling style; they do not guarantee reach, engagement or follower growth.</p>

